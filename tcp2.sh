
#!/usr/bin/env bash
set -Eeuo pipefail

# ==========================================================
# 多用户代理服务器 TCP 优化
# 适用：Linux / Debian / Ubuntu / VLESS Reality / Xray
# 模式：100ms 亚太线路 / 200ms 美西线路
# 安全：不覆盖 /etc/sysctl.conf，不强制修改网卡参数
# ==========================================================

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
RESET='\033[0m'

CONF="/etc/sysctl.d/99-proxy-tuning.conf"
TS="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="/root/tcp-optimize-backup-${TS}"

if [[ $EUID -ne 0 ]]; then
    echo -e "${RED}请使用 root 运行此脚本。${RESET}"
    exit 1
fi

echo -e "${GREEN}多用户代理服务器网络优化${RESET}"
echo "1) 100ms：亚太线路，均衡低延迟与吞吐"
echo "2) 200ms：美西线路，偏重长距离 TCP 吞吐"
echo "3) 查看当前 TCP 参数，不修改系统"
read -rp "请选择 (1-3): " choice

case "$choice" in
    1)
        PROFILE="100ms-Asia"
        RMAX=33554432
        WMAX=33554432
        RDEFAULT=1048576
        WDEFAULT=1048576
        TCP_RMEM="4096 524288 33554432"
        TCP_WMEM="4096 524288 33554432"
        SOMAXCONN=16384
        BACKLOG=16384
        OPTMEM=16777216
        ;;
    2)
        PROFILE="200ms-US-West"
        RMAX=67108864
        WMAX=67108864
        RDEFAULT=2097152
        WDEFAULT=2097152
        TCP_RMEM="4096 1048576 67108864"
        TCP_WMEM="4096 1048576 67108864"
        SOMAXCONN=32768
        BACKLOG=32768
        OPTMEM=16777216
        ;;
    3)
        echo "当前拥塞控制：$(sysctl -n net.ipv4.tcp_congestion_control)"
        echo "默认队列算法：$(sysctl -n net.core.default_qdisc)"
        echo "接收缓冲区：$(sysctl -n net.ipv4.tcp_rmem)"
        echo "发送缓冲区：$(sysctl -n net.ipv4.tcp_wmem)"
        echo "TCP 内存页阈值：$(sysctl -n net.ipv4.tcp_mem)"
        if command -v tc >/dev/null 2>&1; then
            echo
            echo "当前网卡队列："
            tc qdisc show
        fi
        exit 0
        ;;
    *)
        echo -e "${RED}无效选项。${RESET}"
        exit 1
        ;;
esac

echo
echo -e "${YELLOW}即将应用：${PROFILE}${RESET}"
echo "TCP 缓冲区最大值：接收 ${RMAX} / 发送 ${WMAX} 字节"
echo "默认队列算法：fq"
echo "TCP 拥塞控制：BBR"
echo

read -rp "确认继续？(y/N): " confirm
[[ "$confirm" =~ ^[Yy]$ ]] || exit 0

# 检查内核是否支持 BBR
if ! sysctl -n net.ipv4.tcp_available_congestion_control \
    | grep -qw bbr; then
    modprobe tcp_bbr 2>/dev/null || true
fi

if ! sysctl -n net.ipv4.tcp_available_congestion_control \
    | grep -qw bbr; then
    echo -e "${RED}当前内核不支持 BBR，未修改配置。${RESET}"
    exit 1
fi

# 备份本脚本管理的配置，不覆盖原有 sysctl.conf
mkdir -p "$BACKUP_DIR"
if [[ -f "$CONF" ]]; then
    cp -a "$CONF" "$BACKUP_DIR/previous.conf"
    echo "已备份旧优化配置：$BACKUP_DIR/previous.conf"
else
    touch "$BACKUP_DIR/no-previous-config"
fi

# 生成独立配置文件
cat > "$CONF" <<EOF
# Generated by tcp-optimize.sh
# Profile: ${PROFILE}

# 通用队列与网络缓冲
net.core.rmem_max = ${RMAX}
net.core.wmem_max = ${WMAX}
net.core.rmem_default = ${RDEFAULT}
net.core.wmem_default = ${WDEFAULT}
net.core.optmem_max = ${OPTMEM}

net.core.somaxconn = ${SOMAXCONN}
net.core.netdev_max_backlog = ${BACKLOG}

# TCP 自动调节缓冲区
net.ipv4.tcp_rmem = ${TCP_RMEM}
net.ipv4.tcp_wmem = ${TCP_WMEM}

# TCP 拥塞控制
net.ipv4.tcp_congestion_control = bbr
net.core.default_qdisc = fq

# TCP 窗口与路径 MTU
net.ipv4.tcp_window_scaling = 1
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_fastopen = 3

# 连接管理
net.ipv4.tcp_max_syn_backlog = ${SOMAXCONN}
net.ipv4.tcp_fin_timeout = 30
net.ipv4.ip_local_port_range = 1024 65535

# 保守的 TCP Keepalive 参数
net.ipv4.tcp_keepalive_time = 600
net.ipv4.tcp_keepalive_intvl = 30
net.ipv4.tcp_keepalive_probes = 3

# 文件句柄系统上限
fs.file-max = 1048576
fs.nr_open = 1048576
EOF

# 应用失败则回滚本次文件修改
if ! sysctl -p "$CONF"; then
    echo -e "${RED}参数应用失败，正在回滚。${RESET}"

    if [[ -f "$BACKUP_DIR/previous.conf" ]]; then
        cp -a "$BACKUP_DIR/previous.conf" "$CONF"
        sysctl -p "$CONF" || true
    else
        rm -f "$CONF"
    fi

    exit 1
fi

echo
echo -e "${GREEN}配置已应用：${PROFILE}${RESET}"
echo "配置文件：$CONF"
echo "备份目录：$BACKUP_DIR"
echo
echo "实际运行参数："
sysctl net.ipv4.tcp_congestion_control
sysctl net.core.default_qdisc
sysctl net.ipv4.tcp_rmem
sysctl net.ipv4.tcp_wmem
sysctl net.ipv4.tcp_mtu_probing

echo
echo -e "${YELLOW}注意事项：${RESET}"
echo "1. 未修改现有网卡的活动队列，default_qdisc 不一定立即改变活动队列。"
echo "2. 未覆盖 /etc/sysctl.conf；其中若存在同名参数，可能造成启动时配置冲突。"
echo "3. 未强行修改 ethtool、conntrack 和全局文件描述符限制。"
echo "4. 建议在低峰期测试，观察下载速度、丢包、CPU 与内存。"
